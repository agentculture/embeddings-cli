#!/usr/bin/env python3
"""Direct pair-distance measurement for the eidetic-embedder study.

This is the study's one piece of **ad-hoc measurement**: no CLI verb emits a
table of distances between named pairs of atlas items, so this script reads the
committed atlases directly and computes cosine distances over their stored
vectors. Everything else in the study is produced by ``embeddings`` verbs, and
the study labels which numbers came from where.

It is honest measurement rather than re-embedding: vectors are read out of the
atlas exactly as ``survey`` wrote them, so the numbers here sit on the *inside*
of the atlas reproducibility boundary described in
``docs/design-notes/semantic-measurement.md`` section 4 and are exactly
reproducible from the committed atlases (once the git-ignored ``.npy`` sidecars
are regenerated by re-running ``survey``).

Usage, from the repository root:

    uv run python docs/studies/measure_pairs.py

Reads ``docs/studies/atlas-plain`` and ``docs/studies/atlas-instruct``. Writes
nothing; prints a report to stdout.
"""

from __future__ import annotations

import json
import math
import re
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))

from probes import FACTS, VARIANTS  # noqa: E402  (path set up immediately above)

HERE = Path(__file__).resolve().parent
CELLS = ("para_high", "para_low", "contra_high", "contra_low")
CELL_LABEL = {
    "para_high": "same meaning, high overlap",
    "para_low": "same meaning, low overlap",
    "contra_high": "contradicts, high overlap",
    "contra_low": "contradicts, low overlap",
}


def load_atlas(path: Path):
    """Return {record_id: unit-normalised vector} for the atlas at PATH."""
    vectors = np.load(path / "vectors.npy")
    ids = []
    with (path / "records.jsonl").open(encoding="utf-8") as handle:
        for line in handle:
            line = line.strip()
            if line:
                ids.append(json.loads(line)["id"])
    if len(ids) != vectors.shape[0]:
        raise SystemExit(f"{path}: {len(ids)} records but {vectors.shape[0]} vectors")
    norms = np.linalg.norm(vectors, axis=1, keepdims=True)
    unit = vectors / np.where(norms == 0, 1.0, norms)
    return dict(zip(ids, unit)), vectors.shape


def cosine_distance(a, b) -> float:
    return float(1.0 - np.dot(a, b))


def tokens(text: str) -> set[str]:
    return set(re.findall(r"[a-z0-9][a-z0-9.\-/]*", text.lower()))


def jaccard(a: str, b: str) -> float:
    ta, tb = tokens(a), tokens(b)
    union = ta | tb
    return len(ta & tb) / len(union) if union else 0.0


def describe(values: list[float]) -> dict:
    array = np.array(values, dtype=float)
    return {
        "n": int(array.size),
        "mean": float(array.mean()),
        "sd": float(array.std(ddof=1)) if array.size > 1 else 0.0,
        "min": float(array.min()),
        "max": float(array.max()),
        "median": float(np.median(array)),
    }


def row(label: str, stats: dict) -> str:
    return (
        f"| {label:<28} | {stats['n']:>3} | {stats['mean']:.4f} | {stats['sd']:.4f} "
        f"| {stats['min']:.4f} | {stats['median']:.4f} | {stats['max']:.4f} |"
    )


def header() -> str:
    return (
        "| cell                         |   n |   mean |     sd |    min | median |    max |\n"
        "|------------------------------|----:|-------:|-------:|-------:|-------:|-------:|"
    )


def overlap_fraction(lower: list[float], upper: list[float]) -> tuple[float, float]:
    """Fraction of LOWER at or above min(UPPER), and of UPPER at or below max(LOWER)."""
    if not lower or not upper:
        return 0.0, 0.0
    up_min, low_max = min(upper), max(lower)
    above = sum(1 for value in lower if value >= up_min) / len(lower)
    below = sum(1 for value in upper if value <= low_max) / len(upper)
    return above, below


def pearson(xs: list[float], ys: list[float]) -> float:
    x = np.array(xs, dtype=float)
    y = np.array(ys, dtype=float)
    if x.size < 2 or x.std() == 0 or y.std() == 0:
        return float("nan")
    return float(np.corrcoef(x, y)[0, 1])


def cell_distances(vectors, condition: str, other=None) -> dict[str, list[float]]:
    """Distances from each fact's base to each variant, under one condition.

    ``plain``      -- both sides from the plain atlas.
    ``symmetric``  -- both sides from the instruction-prefixed atlas.
    ``asymmetric`` -- stored record plain, query side instruction-prefixed.
    """
    out: dict[str, list[float]] = {cell: [] for cell in CELLS}
    for fact in FACTS:
        base_id = f"{fact['id']}-base"
        base = vectors[base_id] if condition != "symmetric" else other[base_id]
        if condition == "plain":
            base = vectors[base_id]
        for variant in VARIANTS:
            variant_id = f"{fact['id']}-{variant.replace('_', '-')}"
            if condition == "plain":
                far = vectors[variant_id]
            else:
                far = other[variant_id]
            out[variant].append(cosine_distance(base, far))
    return out


def main() -> int:
    plain, plain_shape = load_atlas(HERE / "atlas-plain")
    instructed, _ = load_atlas(HERE / "atlas-instruct")

    print(f"atlas-plain    : {plain_shape[0]} x {plain_shape[1]}")
    print(f"atlas-instruct : {len(instructed)} records\n")

    # ---------------------------------------------------------- baselines --
    control_ids = [cid for cid in plain if cid.startswith("c")]
    control_pairs = [
        cosine_distance(plain[a], plain[b])
        for i, a in enumerate(sorted(control_ids))
        for b in sorted(control_ids)[i + 1 :]
    ]
    base_ids = sorted(f"{fact['id']}-base" for fact in FACTS)
    cross_fact = [
        cosine_distance(plain[a], plain[b])
        for i, a in enumerate(base_ids)
        for b in base_ids[i + 1 :]
    ]

    print("## Baselines (plain atlas)\n")
    print(header())
    print(row("unrelated controls", describe(control_pairs)))
    print(row("cross-fact bases", describe(cross_fact)))
    print()

    # ------------------------------------------------- the 2x2 factorial --
    plain_cells = cell_distances(plain, "plain")
    print("## 2x2 factorial, plain (no instruction prefix)\n")
    print(header())
    for cell in CELLS:
        print(row(CELL_LABEL[cell], describe(plain_cells[cell])))
    print()

    for kind in ("value", "negation"):
        keep = [index for index, fact in enumerate(FACTS) if fact["kind"] == kind]
        print(f"### split: {kind} facts only\n")
        print(header())
        for cell in CELLS:
            subset = [plain_cells[cell][index] for index in keep]
            print(row(CELL_LABEL[cell], describe(subset)))
        print()

    # ------------------------------------------------- distribution overlap --
    print("## Distribution overlap (plain)\n")
    checks = [
        ("contra_high", "para_low", "contradiction+high-overlap vs paraphrase+low-overlap"),
        ("contra_low", "para_high", "contradiction+low-overlap vs paraphrase+high-overlap"),
        ("contra_high", "para_high", "within high overlap: contradiction vs paraphrase"),
        ("contra_low", "para_low", "within low overlap: contradiction vs paraphrase"),
    ]
    for lower, upper, label in checks:
        low_values, up_values = plain_cells[lower], plain_cells[upper]
        above, below = overlap_fraction(low_values, up_values)
        separated = "SEPARATED" if above == 0.0 and below == 0.0 else "OVERLAP"
        print(f"- {label}: {separated}")
        print(
            f"  - {lower} mean {np.mean(low_values):.4f} "
            f"[{min(low_values):.4f}, {max(low_values):.4f}]"
        )
        print(
            f"  - {upper} mean {np.mean(up_values):.4f} "
            f"[{min(up_values):.4f}, {max(up_values):.4f}]"
        )
        print(
            f"  - {above * 100:.0f}% of {lower} at or above min({upper}); "
            f"{below * 100:.0f}% of {upper} at or below max({lower})"
        )
    print()

    # ------------------------------------------------------ recall inversion --
    print("## Per-fact recall inversion (plain)\n")
    print("Does the contradicting near-duplicate outrank the low-overlap paraphrase?\n")
    inverted = []
    for index, fact in enumerate(FACTS):
        ch = plain_cells["contra_high"][index]
        pl = plain_cells["para_low"][index]
        if ch < pl:
            inverted.append(fact["id"])
    print(
        f"- contra_high closer than para_low for {len(inverted)}/{len(FACTS)} facts: "
        f"{', '.join(inverted) if inverted else 'none'}"
    )
    inverted_low = [
        fact["id"]
        for index, fact in enumerate(FACTS)
        if plain_cells["contra_low"][index] < plain_cells["para_high"][index]
    ]
    print(
        f"- contra_low closer than para_high for {len(inverted_low)}/{len(FACTS)} facts: "
        f"{', '.join(inverted_low) if inverted_low else 'none'}"
    )
    print()

    # ------------------------------------------------------ lexical overlap --
    print("## Lexical overlap vs distance (plain)\n")
    overlaps: list[float] = []
    distances: list[float] = []
    contradicts: list[float] = []
    per_cell_overlap = {cell: [] for cell in CELLS}
    for index, fact in enumerate(FACTS):
        for cell in CELLS:
            value = jaccard(fact["base"], fact[cell])
            per_cell_overlap[cell].append(value)
            overlaps.append(value)
            distances.append(plain_cells[cell][index])
            contradicts.append(1.0 if cell.startswith("contra") else 0.0)
    print("| cell                         | mean token Jaccard vs base |")
    print("|------------------------------|---------------------------:|")
    for cell in CELLS:
        print(f"| {CELL_LABEL[cell]:<28} | {np.mean(per_cell_overlap[cell]):.4f} |")
    print()
    print(f"- Pearson r(lexical overlap, distance)   = {pearson(overlaps, distances):+.4f}")
    print(f"- Pearson r(contradicts, distance)       = {pearson(contradicts, distances):+.4f}")
    print(f"- Pearson r(lexical overlap, contradicts) = {pearson(overlaps, contradicts):+.4f}")

    # Partial correlation of contradiction with distance, controlling overlap.
    r_cd = pearson(contradicts, distances)
    r_od = pearson(overlaps, distances)
    r_oc = pearson(overlaps, contradicts)
    denominator = math.sqrt((1 - r_od**2) * (1 - r_oc**2))
    partial = (r_cd - r_od * r_oc) / denominator if denominator else float("nan")
    print(f"- partial r(contradicts, distance | overlap) = {partial:+.4f}")
    print()

    # -------------------------------------------------- instruction prefix --
    print("## Instruction-prefix conditions\n")
    symmetric = cell_distances(instructed, "symmetric", instructed)
    asymmetric = cell_distances(plain, "asymmetric", instructed)
    for name, cells in (
        ("plain (neither side prefixed)", plain_cells),
        ("symmetric (both sides prefixed)", symmetric),
        ("asymmetric (stored plain, query prefixed)", asymmetric),
    ):
        print(f"### {name}\n")
        print(header())
        for cell in CELLS:
            print(row(CELL_LABEL[cell], describe(cells[cell])))
        gap = np.mean(cells["para_low"]) - np.mean(cells["contra_high"])
        flips = sum(
            1
            for index in range(len(FACTS))
            if cells["contra_high"][index] < cells["para_low"][index]
        )
        print()
        print(f"- mean(para_low) - mean(contra_high) = {gap:+.4f} (positive = inversion holds)")
        print(f"- inversion holds for {flips}/{len(FACTS)} facts")
        print()

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
